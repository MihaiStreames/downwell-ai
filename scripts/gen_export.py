_OUT_DIR: Final[Path] = Path(__file__).parent / "generated"
_GAME_FPS: Final[int] = 60
_DEFAULT_SPEED: Final[int] = 0
# upper bound on object indices; the flag table is filled until object_exists() fails
_OBJECT_LIMIT: Final[int] = 1024

_HEADER: Final[str] = "AUTO-GENERATED by scripts/gen_export.py from downwell_ai/env/memory/layout.py, do not edit by hand"

# gml expression per header field; `_p` is the player instance and only read when `_has_player`
_HEADER_EXPRESSIONS: Final[dict[str, str]] = {
    "frame": "global.dqn_frame",
    "room": "room",
    "has_player": "_has_player",
    "xpos": '_has_player ? (variable_instance_exists(_p, "xx") ? _p.xx : _p.x) : 0',
    "ypos": '_has_player ? (variable_instance_exists(_p, "yy") ? _p.yy : _p.y) : 0',
    "vx": '(_has_player && variable_instance_exists(_p, "xsp")) ? _p.xsp : 0',
    "vy": '(_has_player && variable_instance_exists(_p, "ysp")) ? _p.ysp : 0',
    "grounded": '(_has_player && variable_instance_exists(_p, "grounded")) ? _p.grounded : 0',
    "inwater": '(_has_player && variable_instance_exists(_p, "inWater")) ? _p.inWater : 0',
    "hp": "global.playerHp",
    "hp_max": "global.playerHpMax",
    "ammo": "global.stammo",
    "ammo_max": "global.ammo",
    "gems": "global.currency",
    "combo": "global.comboCount",
    "area": "global.area",
    "level": "global.level",
    "death": "global.death",
    "in_side_room": "global.pTimeStop",
    "menu": "_menu",
    "cursor": "_cursor",
    "shop": "(_shop != noone) ? 1 : 0",
    "shop_cursor": "(_shop != noone) ? _shop.cursorAt : 0",
    "view_x": "camera_get_view_x(view_camera[0])",
    "view_y": "camera_get_view_y(view_camera[0])",
    "view_w": "camera_get_view_width(view_camera[0])",
    "view_h": "camera_get_view_height(view_camera[0])",
}

# gml expression per record field, evaluated inside `with (all)`; the variable lookups only run for DETAIL_FLAGS
_RECORD_EXPRESSIONS: Final[dict[str, str]] = {
    "id": "id",
    "object": "object_index",
    "flags": "_f",
    "x": "x",
    "y": "y",
    "left": "bbox_left",
    "top": "bbox_top",
    "right": "bbox_right",
    "bottom": "bbox_bottom",
    "vx": 'variable_instance_exists(id, "xsp") ? xsp : 0',
    "vy": 'variable_instance_exists(id, "ysp") ? ysp : 0',
    "hp": 'variable_instance_exists(id, "ehp") ? ehp : 0',
    "yy": 'variable_instance_exists(id, "yy") ? yy : y',
    "white": 'variable_instance_exists(id, "white") ? white : 0',
    "angry": 'variable_instance_exists(id, "angry") ? angry : 0',
    "immune": 'variable_instance_exists(id, "bulletImmune") ? bulletImmune : 0',
}
_ALWAYS_WRITTEN: Final[tuple[str, ...]] = ("id", "object", "flags", "x", "y", "left", "top", "right", "bottom")


def build_control() -> str:
    return f"""// {_HEADER}
global.dqn_cmagic = 161803.3988;
if (!variable_global_exists("dqn_ctrl")) {{
    global.dqn_ctrl = 0;
    global.dqn_act = 0;
    global.dqn_prev_act = 0;
    global.dqn_step = 0;
    global.dqn_done = 0;
    global.dqn_ready = 0;
    global.dqn_repeat = 1;
    global.dqn_left = 0;
    global.dqn_reset = 0;
    global.dqn_seed = -1;
    global.dqn_timeout_ms = 2000;
    global.dqn_headless = 0;
    global.dqn_headless_on = 0;
}}
if (global.dqn_headless != global.dqn_headless_on) {{
    global.dqn_headless_on = global.dqn_headless;
    draw_enable_drawevent(!global.dqn_headless);
    display_reset(0, !global.dqn_headless);
    audio_master_gain(global.dqn_headless ? 0 : 1);
}}
if (global.dqn_ctrl && global.dqn_left <= 0) {{
    if (global.dqn_ready != global.dqn_done) global.dqn_ready = global.dqn_done;
    var _deadline = get_timer() + global.dqn_timeout_ms * 1000;
    while (global.dqn_step == global.dqn_done && get_timer() < _deadline) {{ }}
    if (global.dqn_step == global.dqn_done) {{
        global.dqn_ctrl = 0;
        global.dqn_headless = 0;
        global.dqn_speed = 0;
        room_speed = {_GAME_FPS};
    }} else {{
        global.dqn_done = global.dqn_step;
        global.dqn_left = max(1, global.dqn_repeat);
        if (global.dqn_reset) {{
            global.dqn_reset = 0;
            // a seed >= 0 makes the next run reproducible, then is consumed
            if (global.dqn_seed >= 0) {{
                random_set_seed(global.dqn_seed);
                global.dqn_seed = -1;
            }}
            ResetPlayer();
            scrNextLevel(1);
        }}
    }}
}}
if (global.dqn_ctrl) {{
    var _l = (global.dqn_act & 1) != 0, _r = (global.dqn_act & 2) != 0, _j = (global.dqn_act & 4) != 0;
    var _pl = (global.dqn_prev_act & 1) != 0, _pr = (global.dqn_prev_act & 2) != 0, _pj = (global.dqn_prev_act & 4) != 0;
    global.dLeft = _l;
    global.dLeftPressed = _l && !_pl;
    global.dRight = _r;
    global.dRightPressed = _r && !_pr;
    global.dUp = _j && !_pj;
    global.dUpHeld = _j;
    global.dUpRel = !_j && _pj;
    global.anyInput = global.dUp || global.dLeftPressed || global.dRightPressed;
    global.dqn_prev_act = global.dqn_act;
    global.dqn_left = global.dqn_left - 1;
}}
"""


def _flag_table() -> str:
    """Once per game: the buffer, its published address, and the family bits of every object index."""
    checks = []
    for flag, roots in FAMILY_ROOTS.items():
        condition = " || ".join(f"_o == {root} || object_is_ancestor(_o, {root})" for root in roots)
        checks.append(f"        if ({condition}) _f |= {flag};")
    listed = " || ".join(f"_o == {name}" for name in LISTED_OBJECTS)
    checks.append(f"        if ({listed}) _f |= {FLAG_LISTED};")
    lines = "\n".join(checks)
    return f"""if (!variable_global_exists("dqn_buf")) {{
    global.dqn_buf = buffer_create({BUFFER_BYTES}, buffer_fixed, 4);
    global.dqn_buf_addr = buffer_get_address(global.dqn_buf);
    global.dqn_flags = array_create({_OBJECT_LIMIT}, 0);
    var _o = 0;
    while (_o < {_OBJECT_LIMIT} && object_exists(_o)) {{
        var _f = 0;
{lines}
        global.dqn_flags[_o] = _f;
        _o += 1;
    }}
}}"""


def _write(expression: str, indent: str = "") -> str:
    return f"{indent}buffer_write(_b, buffer_f32, {expression});"


def _record_body() -> str:
    always = "\n".join(_write(_RECORD_EXPRESSIONS[name], "        ") for name in _ALWAYS_WRITTEN)
    detailed_fields = [name for name in RECORD_FIELDS if name not in _ALWAYS_WRITTEN]
    detailed = "\n".join(_write(_RECORD_EXPRESSIONS[name], "            ") for name in detailed_fields)
    return f"""{always}
        if (_f & {DETAIL_FLAGS}) {{
{detailed}
        }} else {{
            repeat ({len(detailed_fields)}) buffer_write(_b, buffer_f32, 0);
        }}"""


def _export_body() -> str:
    header = "\n".join(_write(_HEADER_EXPRESSIONS[name]) for name in HEADER_FIELDS)
    offers = "\n".join(_write(f"(_result != noone && {slot} <= _result.levelUgMax) ? _result.levelUg[{slot}] : -1") for slot in range(OFFER_SLOTS))
    prices = "\n".join(_write(f"(_shop != noone) ? _shop.itemPrice[{slot}] : 0") for slot in range(SHOP_SLOTS))
    owned = "\n".join(_write(f'variable_global_exists("ug") ? global.ug[{upgrade}][1] : 0') for upgrade in range(N_UPGRADES))
    return f"""var _b = global.dqn_buf;
buffer_seek(_b, buffer_seek_start, 0);
var _has_player = instance_exists(objPlayer_n);
var _p = _has_player ? instance_find(objPlayer_n, 0) : noone;
var _result = instance_exists(Result) ? instance_find(Result, 0) : noone;
var _menu = (_result != noone && _result.showLevelUp && !_result.inputWait) ? 1 : 0;
var _cursor = (_result != noone) ? _result.cursorAt : 0;
var _shop = instance_exists(Shop) ? instance_find(Shop, 0) : noone;
{header}
{offers}
{prices}
{owned}
var _count_at = buffer_tell(_b);
buffer_write(_b, buffer_f32, 0);
var _n = 0;
with (all) {{
    var _f = global.dqn_flags[object_index];
    if (_f != 0 && _n < {MAX_RECORDS}) {{
{_record_body()}
        _n += 1;
    }}
}}
buffer_poke(_b, _count_at, buffer_f32, _n);"""


def _export_prelude() -> str:
    return f"""// {_HEADER}
global.dqn_magic = 271828.1828;
if (!variable_global_exists("dqn_frame")) global.dqn_frame = 0;
global.dqn_frame = global.dqn_frame + 1;
if (!variable_global_exists("dqn_speed")) global.dqn_speed = {_DEFAULT_SPEED};
if (global.dqn_speed > 0) room_speed = global.dqn_speed;"""


# the runner applies view following in the render phase, headless skips it and objBuilder never builds below the view;
# same rule as the runner (checked to match it exactly), applied only when headless
def _view_follow() -> str:
    return """var _cam = view_camera[0], _t = camera_get_view_target(_cam);
if (global.dqn_headless_on && _t != noone && instance_exists(_t)) {
    var _vx = camera_get_view_x(_cam), _vy = camera_get_view_y(_cam);
    var _vw = camera_get_view_width(_cam), _vh = camera_get_view_height(_cam);
    var _bx = camera_get_view_border_x(_cam), _by = camera_get_view_border_y(_cam);
    var _sx = camera_get_view_speed_x(_cam), _sy = camera_get_view_speed_y(_cam);
    var _nx = _vx, _ny = _vy;
    if (2 * _bx >= _vw) _nx = _t.x - _vw / 2;
    else if (_t.x - _bx < _nx) _nx = _t.x - _bx;
    else if (_t.x + _bx > _nx + _vw) _nx = _t.x + _bx - _vw;
    if (2 * _by >= _vh) _ny = _t.y - _vh / 2;
    else if (_t.y - _by < _ny) _ny = _t.y - _by;
    else if (_t.y + _by > _ny + _vh) _ny = _t.y + _by - _vh;
    if (_sx >= 0) _nx = _vx + clamp(_nx - _vx, -_sx, _sx);
    if (_sy >= 0) _ny = _vy + clamp(_ny - _vy, -_sy, _sy);
    _nx = clamp(_nx, 0, room_width - _vw);
    _ny = clamp(_ny, 0, room_height - _vh);
    camera_set_view_pos(_cam, _nx, _ny);
}"""


def build_export() -> str:
    # the agent only reads a step's last frame, so the export skips the others
    gated = ["if (!global.dqn_ctrl || global.dqn_left <= 0) {", textwrap.indent(_export_body(), "    "), "}"]
    # last statement: the reader may read as soon as ready changes
    handshake = "if (global.dqn_ctrl && global.dqn_left <= 0) global.dqn_ready = global.dqn_done;"
    return "\n".join([_export_prelude(), _view_follow(), _flag_table(), *gated, handshake]) + "\n"


# AppendGML because CodeImportGroup doesn't exist in UndertaleModTool 0.5.x
def build_csx() -> str:
    return f"""// {_HEADER}
EnsureDataLoaded();
string dir = Path.GetDirectoryName(ScriptPath);
Data.Code.ByName("gml_Object_objControlerN_Step_1").AppendGML(File.ReadAllText(Path.Combine(dir, "dqn_control.gml")), Data);
Data.Code.ByName("gml_Object_objControlerN_Step_2").AppendGML(File.ReadAllText(Path.Combine(dir, "dqn_export.gml")), Data);
ScriptMessage("DQN control + exporter injected. Save the data.win (File > Save) and launch the game.");
"""


def main() -> None:
    _OUT_DIR.mkdir(exist_ok=True)
    outputs = {
        _OUT_DIR / "dqn_control.gml": build_control(),
        _OUT_DIR / "dqn_export.gml": build_export(),
        _OUT_DIR / "InjectDQNExport.csx": build_csx(),
    }
    for path, text in outputs.items():
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
