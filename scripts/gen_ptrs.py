import os
import struct
import sys


sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from PyMemoryEditor import OpenProcess
from downwell_ai.env.memory._module_base import resolve_module_base


_REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_OUT = os.path.join(_REPO, "downwell_ai", "env", "memory", "generated", "game_ptrs.py")
_DW = os.environ.get("DOWNWELL_DATA_WIN", r"E:\SteamLibrary\steamapps\common\Downwell\data.win")

_PROCESS = "Downwell.exe"
_MAGIC = 271828.1828
_CONTROL_MAGIC = 161803.3988

_STATIC_OFF, _OBJ_OFF, _ELEMS_OFF, _SIZE_OFF = 0x547A08, 0x24, 0x10, 0x0
ESZ, KEY_OFF = 12, 4

_FIELDS = [
    ("buf_addr", "dqn_buf_addr"),
    ("frame", "dqn_frame"),
    ("speed", "dqn_speed"),
    ("ctrl", "dqn_ctrl"),
    ("act", "dqn_act"),
    ("step", "dqn_step"),
    ("done", "dqn_done"),
    ("ready", "dqn_ready"),
    ("repeat", "dqn_repeat"),
    ("reset", "dqn_reset"),
    ("seed", "dqn_seed"),
    ("timeout_ms", "dqn_timeout_ms"),
    ("headless", "dqn_headless"),
]


def load_var_slots(data_win: str) -> tuple[dict[str, int], list[int]]:
    raw = open(data_win, "rb").read()
    pos, chunks = 8, {}

    while pos < len(raw):
        size = struct.unpack_from("<I", raw, pos + 4)[0]
        chunks[raw[pos : pos + 4].decode()] = (pos + 8, size)
        pos += 8 + size

    vo, vs = chunks["VARI"]
    out, q = {}, vo + 12  # 3 header ints, then 20-byte entries
    keyed_ids = set()

    while q + 20 <= vo + vs:
        name_ptr, inst_type, var_id = struct.unpack_from("<Iii", raw, q)
        if name_ptr == 0:
            break

        n = struct.unpack_from("<I", raw, name_ptr - 4)[0]
        name = raw[name_ptr : name_ptr + n].decode("utf-8", "replace")
        if inst_type == -5:
            out[name] = var_id
        if inst_type != -7:
            keyed_ids.add(var_id)

        q += 20

    return out, sorted(keyed_ids)


def main() -> None:
    slots, keyed_ids = load_var_slots(_DW)
    proc = OpenProcess(name=_PROCESS)
    base = resolve_module_base(proc, _PROCESS)
    if base is None:
        sys.exit("could not resolve module base - is the game running?")

    def u32(addr: int) -> int:
        return struct.unpack_from("<I", proc.read_process_memory(addr, bytes, 4))[0]

    obj = u32(base + _STATIC_OFF)
    hashmap = u32(obj + _OBJ_OFF)
    size = struct.unpack_from("<i", proc.read_process_memory(hashmap + _SIZE_OFF, bytes, 4))[0]
    elems = u32(hashmap + _ELEMS_OFF)
    raw = proc.read_process_memory(elems, bytes, size * ESZ)

    bucket_of: dict[int, int] = {}
    kind_of: dict[int, int] = {}
    magic_key = None
    control_key = None

    for j in range(size):
        ptr = struct.unpack_from("<I", raw, j * ESZ)[0]
        if not ptr:
            continue

        key = struct.unpack_from("<i", raw, j * ESZ + KEY_OFF)[0]
        bucket_of[key] = j

        rvalue = proc.read_process_memory(ptr, bytes, 16)
        kind_of[key] = struct.unpack_from("<I", rvalue, 12)[0] & 0xFFFFFF
        if kind_of[key] != 0:
            continue

        value = struct.unpack_from("<d", rvalue, 0)[0]
        if abs(value - _MAGIC) < 1e-6:
            magic_key = key
        if abs(value - _CONTROL_MAGIC) < 1e-6:
            control_key = key

    if magic_key is None or control_key is None:
        sys.exit("dqn fingerprints not found - is the game running the data.win patched with InjectDQNExport.csx?")

    # map keys run consecutively over the var ids that exist (any type but locals), the ids themselves have holes,
    # so count from the nearest fingerprint at or below
    rank = {var_id: i for i, var_id in enumerate(keyed_ids)}
    anchors = sorted([(slots["dqn_magic"], magic_key), (slots["dqn_cmagic"], control_key)])

    def key_for(var_id: int) -> int:
        below = [(anchor_id, key) for anchor_id, key in anchors if anchor_id <= var_id]
        if not below:
            sys.exit(f"var id {var_id} precedes every fingerprint - regenerate with scripts/gen_export.py and re-inject")

        anchor_id, key = below[-1]
        return key + rank[var_id] - rank[anchor_id]

    keymap = {n: key_for(v) for n, v in slots.items() if n.startswith("dqn_")}

    lines, missing = [], []

    for field, gname in _FIELDS:
        key = keymap.get(gname)
        if key is None or key not in bucket_of:
            missing.append(field)
            continue

        if kind_of[key] not in (0, 3, 7, 10, 13):
            print(f"warning: {field} ({gname}) has RValue kind {kind_of[key]}, _rvalue.py only decodes REAL, PTR, INT32, INT64 and BOOL")

        lines.append(f'    "{field}": 0x{bucket_of[key] * ESZ:X},')

    header = f"""# AUTO-GENERATED by scripts/gen_*.py, do not edit by hand

from typing import Final


GLOBALS_BASE: Final[int] = 0x{_STATIC_OFF:08X}  # module offset of the global object pointer
MAP_CHAIN: Final[tuple[int, ...]] = (0x{_OBJ_OFF:X}, 0x{_ELEMS_OFF:X})  # global object -> variable map -> elements array

FIELD_OFFSETS: Final[dict[str, int]] = {{
"""
    with open(_OUT, "w", newline="\n") as fh:
        fh.write(header + "\n".join(lines) + "\n}\n")

    print(f"wrote {_OUT}: {len(lines)} fields, map size {size}")
    if missing:
        print(f"missing (not in the live map yet - start a run and rerun): {missing}")


if __name__ == "__main__":
    main()
